// Helper: translate foot value stored in DB (always French) to display label
export function translateFoot(foot: string, lang: Lang): string {
  if (lang === 'fr') return foot
  const map: Record<string, string> = {
    'Droit': 'Rechts',
    'Gauche': 'Links',
    'Ambidextre': 'Beidfüssig',
  }
  return map[foot] ?? foot
}

// Helper: full foot display label (e.g. "Pied droit" / "Rechts")
export function footDisplay(foot: string, lang: Lang): string {
  if (lang === 'fr') return `Pied ${foot.toLowerCase()}`
  const map: Record<string, string> = {
    'Droit': 'Rechter Fuss',
    'Gauche': 'Linker Fuss',
    'Ambidextre': 'Beidfüssig',
  }
  return map[foot] ?? foot
}

// Helper function
export function tr(key: { fr: string; de: string }, lang: Lang): string {
  return key[lang]
}
